-- TripSync PostgreSQL schema
-- Run against a new, empty PostgreSQL database.
-- Do not run against the existing production Neon database.

BEGIN;

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL
);

CREATE TABLE trips (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    trip_name TEXT NOT NULL,
    destination TEXT NOT NULL,
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    budget DOUBLE PRECISION NOT NULL DEFAULT 0
);

CREATE TABLE trip_members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id INTEGER NOT NULL REFERENCES trips(id),
    user_id INTEGER NOT NULL REFERENCES users(id),
    CONSTRAINT trip_members_trip_id_user_id_key UNIQUE (trip_id, user_id)
);

CREATE TABLE pending_invitations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id INTEGER NOT NULL REFERENCES trips(id),
    email TEXT NOT NULL,
    invited_by INTEGER NOT NULL REFERENCES users(id)
);

CREATE TABLE itinerary (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id INTEGER NOT NULL REFERENCES trips(id),
    activity TEXT NOT NULL,
    date TEXT NOT NULL,
    time TEXT NOT NULL,
    location TEXT NOT NULL
);

CREATE TABLE expenses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id INTEGER NOT NULL REFERENCES trips(id),
    description TEXT NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    paid_by INTEGER NOT NULL REFERENCES users(id)
);

CREATE TABLE polls (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id INTEGER NOT NULL REFERENCES trips(id),
    question TEXT NOT NULL
);

CREATE TABLE poll_options (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id INTEGER NOT NULL REFERENCES polls(id),
    option_text TEXT NOT NULL
);

CREATE TABLE poll_votes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id INTEGER NOT NULL REFERENCES polls(id),
    option_id INTEGER NOT NULL REFERENCES poll_options(id),
    user_id INTEGER NOT NULL REFERENCES users(id),
    CONSTRAINT poll_votes_poll_id_user_id_key UNIQUE (poll_id, user_id)
);

CREATE TABLE checklist (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id INTEGER NOT NULL REFERENCES trips(id),
    item TEXT NOT NULL,
    completed INTEGER NOT NULL DEFAULT 0
);

COMMIT;
